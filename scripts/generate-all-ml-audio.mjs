function buildWavHeader(dataSize, sampleRate = 24000, numChannels = 1, bitsPerSample = 16) {
  const byteRate = (sampleRate * numChannels * bitsPerSample) / 8;
  const blockAlign = (numChannels * bitsPerSample) / 8;
  const buf = Buffer.alloc(44);
  buf.write('RIFF', 0);
  buf.writeUInt32LE(36 + dataSize, 4);
  buf.write('WAVE', 8);
  buf.write('fmt ', 12);
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20);
  buf.writeUInt16LE(numChannels, 22);
  buf.writeUInt32LE(sampleRate, 24);
  buf.writeUInt32LE(byteRate, 28);
  buf.writeUInt16LE(blockAlign, 32);
  buf.writeUInt16LE(bitsPerSample, 34);
  buf.write('data', 36);
  buf.writeUInt32LE(dataSize, 40);
  return buf;
}

function extractPcm(wavBuffer) {
  const dataIdx = wavBuffer.indexOf(Buffer.from('data'));
  if (dataIdx === -1) return wavBuffer.slice(44);
  return wavBuffer.slice(dataIdx + 8);
}

const sleep = (ms) => new Promise(res => setTimeout(res, ms));

async function generateStoryMlAudio(storyId, chunks) {
  const outDir = path.resolve(`data/audio/stories/${storyId}`);
  fs.mkdirSync(outDir, { recursive: true });

  console.log(`\n======================================================`);
  console.log(`Generating ML Audio for: ${storyId} (${chunks.length} chunks)...`);
  console.log(`======================================================`);

  const pcmChunks = [];
  for (let i = 0; i < chunks.length; i++) {
    const text = chunks[i];
    const chunkFile = path.join(outDir, `.tmp-ml-chunk-${i + 1}.wav`);
    console.log(`[${storyId}] Synthesizing Chunk ${i + 1}/${chunks.length} (${text.length} chars)...`);

    const result = await synthesizeSpeech({
      text,
      lang: 'ml-IN',
      voice: 'Shivani',
      targetPath: chunkFile
    });

    const chunkBuf = fs.readFileSync(result.filePath);
    const pcm = extractPcm(chunkBuf);
    pcmChunks.push(pcm);

    await sleep(1200); // Respect Gnani rate limits
  }

  const totalPcm = Buffer.concat(pcmChunks);
  const header = buildWavHeader(totalPcm.length);
  const masterWav = Buffer.concat([header, totalPcm]);
  const wavPath = path.join(outDir, 'ml-IN.wav');
  fs.writeFileSync(wavPath, masterWav);

  const durationSec = Math.round(totalPcm.length / (24000 * 2));
  console.log(`Master WAV created: ${wavPath} (~${durationSec}s)`);

  // Clean up temporary chunk files
  for (let i = 0; i < chunks.length; i++) {
    try { fs.unlinkSync(path.join(outDir, `.tmp-ml-chunk-${i + 1}.wav`)); } catch (_) {}
  }

  // Transcode to MP3
  const mp3Path = path.join(outDir, 'ml-IN.mp3');
  console.log(`Transcoding to ${mp3Path}...`);
  execFileSync(ffmpegPkg.path, [
    '-y',
    '-i', wavPath,
    '-codec:a', 'libmp3lame',
    '-b:a', '64k',
    '-ac', '1',
    '-ar', '24000',
    mp3Path
  ], { stdio: 'ignore' });

  // Clean raw wav
  try { fs.unlinkSync(wavPath); } catch (_) {}

  const mp3Size = fs.statSync(mp3Path).size;
  console.log(`✅ MP3 Created: ${mp3Path} (${(mp3Size / 1024 / 1024).toFixed(2)} MB, ${durationSec}s)`);

  // Update DB
  const db = getDb();
  const fullText = chunks.map(c => c.replace(/<[^>]+>/g, '').trim()).join('\n\n');
  const audioRelativePath = `/media/audio/stories/${storyId}/ml-IN.mp3`;

  db.prepare(`
    INSERT INTO story_translations (story_id, lang, body, voice, reviewed, audio_status, audio_path, audio_duration_sec, updated_at)
    VALUES (?, 'ml-IN', ?, 'Shivani', 1, 'ready', ?, ?, datetime('now'))
    ON CONFLICT(story_id, lang) DO UPDATE SET
      body = excluded.body,
      audio_status = 'ready',
      audio_path = excluded.audio_path,
      audio_duration_sec = excluded.audio_duration_sec,
      updated_at = datetime('now')
  `).run(storyId, fullText, audioRelativePath, durationSec);

  console.log(`✅ DB updated for ${storyId} ml-IN (${durationSec}s, ${fullText.length} chars)`);
  return { storyId, mp3Path, mp3Size, durationSec };
}

