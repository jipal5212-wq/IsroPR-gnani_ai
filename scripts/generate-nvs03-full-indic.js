async function synthesizeFullStory(lang, langConfig) {
  const finalPath = path.join(OUT_DIR, `${lang}.wav`);

  // If already generated full master WAV (>20MB), skip
  if (existsSync(finalPath) && statSync(finalPath).size > 20000000) {
    const size = statSync(finalPath).size;
    const durSec = Math.round((size - 44) / (24000 * 2));
    console.log(`⏩ ${langConfig.name} (${lang}) already generated (${(size / 1024 / 1024).toFixed(2)} MB, ~${durSec}s), skipping.`);
    return { lang, durationSec: durSec, sizeMB: (size / (1024 * 1024)).toFixed(2) };
  }

  console.log(`\n============================================================`);
  console.log(`🎙️  Starting Full 14-Chunk Narration for ${langConfig.name} (${lang})...`);
  console.log(`============================================================`);

  const pcmBuffers = [];
  const tempFiles = [];

  for (let i = 0; i < langConfig.chunks.length; i++) {
    const chunk = langConfig.chunks[i];
    const tmpPath = path.join(OUT_DIR, `.tmp-${lang}-chunk-${chunk.num}.wav`);
    tempFiles.push(tmpPath);

    // Reuse existing chunk if valid (>100KB)
    if (existsSync(tmpPath) && statSync(tmpPath).size > 100000) {
      const wavBuf = readFileSync(tmpPath);
      const pcm = extractPcm(wavBuf);
      pcmBuffers.push(pcm);
      const durSec = Math.round(pcm.length / (24000 * 2));
      console.log(`   ⚡ [Cached] Chunk ${chunk.num} reused: ${pcm.length} PCM bytes (~${durSec}s)`);
      continue;
    }

    console.log(`🎙️  [${langConfig.name} Chunk ${chunk.num}/14] "${chunk.title}" (${chunk.text.length} chars)`);

    let success = false;
    let attempts = 0;

    while (!success && attempts < 5) {
      attempts++;
      try {
        await synthesizeSpeech({
          text: chunk.text,
          lang: lang,
          voice: 'Shivani',
          model: 'timbre-v3.0',
          targetPath: tmpPath
        });

        const wavBuf = readFileSync(tmpPath);
        const pcm = extractPcm(wavBuf);
        pcmBuffers.push(pcm);
        const durSec = Math.round(pcm.length / (24000 * 2));
        console.log(`   ✅ Chunk ${chunk.num} done: ${pcm.length} PCM bytes (~${durSec}s)`);
        success = true;

        if (i < langConfig.chunks.length - 1) {
          await new Promise(r => setTimeout(r, 3000)); // 3s pacing between chunks
        }
      } catch (err) {
        console.error(`   ⚠️ Attempt ${attempts}/5 failed: ${err.message}`);
        if (attempts < 5) {
          console.log(`   ⏳ Backing off 12s for server slot to clear...`);
          await new Promise(r => setTimeout(r, 12000));
        } else {
          throw err;
        }
      }
    }
  }

  // Cleanup temp files
  tempFiles.forEach(f => {
    try { rmSync(f, { force: true }); } catch (_) {}
  });

  console.log(`🔨 Concatenating 14 ${langConfig.name} PCM chunks...`);
  const combinedPcm = Buffer.concat(pcmBuffers);
  const header = buildWavHeader(combinedPcm.length);
  const finalWav = Buffer.concat([header, combinedPcm]);

  writeFileSync(finalPath, finalWav);

  const durationSec = Math.round(combinedPcm.length / (24000 * 2));
  const sizeMB = (finalWav.length / (1024 * 1024)).toFixed(2);

  console.log(`✨ ${langConfig.name} Master WAV Generated!`);
  console.log(`   Path: ${finalPath}`);
  console.log(`   Size: ${sizeMB} MB (${finalWav.length} bytes)`);
  console.log(`   Duration: ${Math.floor(durationSec / 60)}m ${durationSec % 60}s (${durationSec} seconds)`);

  // Update SQLite Database
  const db = getDb();
  const fullBodyText = langConfig.chunks.map(c => c.text).join('\n\n');
  db.prepare(`
    UPDATE story_translations
    SET body = ?, audio_path = ?, audio_status = 'ready', audio_duration_sec = ?
    WHERE story_id = 'nvs-03' AND lang = ?
  `).run(fullBodyText, `/media/audio/stories/nvs-03/${lang}.wav`, durationSec, lang);

  console.log(`💾 Database updated for nvs-03 (${lang}): duration = ${durationSec}s`);
  return { lang, durationSec, sizeMB };
}

async function main() {
  const targetLangs = ['ta-IN', 'te-IN', 'bn-IN', 'kn-IN'];
  const results = [];

  for (const lang of targetLangs) {
    const res = await synthesizeFullStory(lang, INDIC_SCRIPTS[lang]);
    results.push(res);
    console.log(`⏸️  Inter-language cooldown 3.0s...`);
    await new Promise(r => setTimeout(r, 3000));
  }

  console.log(`\n============================================================`);
  console.log(`🎉 ALL 4 INDIC LANGUAGES FULLY GENERATED!`);
  console.log(`============================================================`);
  console.table(results);
}

main().catch(err => {
  console.error('Fatal Indic generation error:', err);
  process.exit(1);
});

